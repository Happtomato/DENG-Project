RAW = ROOT / 'data/raw/mediamarkt'


def fixture(sku='2230728'):
    return transform_file(next(RAW.glob(sku + '_*.json')))


class TransformationTests(unittest.TestCase):
    def test_real_legacy_data_and_scope(self):
        items = transform_directory(RAW)
        original = [i for i in items if Path(i['path']).name.split('_')[1].startswith('20261015T')]
        self.assertEqual(len(original),7)
        self.assertEqual(sum('observation' in i for i in original),6)
        rejected = next(i for i in original if '133486101_' in i['path'])
        self.assertIn('excluded_hardware',rejected['rejection'])

    def test_ssd_and_ram_transformations(self):
        self.assertEqual(fixture('2155505')['observation']['brand'],'SAMSUNG')
        self.assertEqual(fixture('2199070')['observation']['brand'],'WESTERN DIGITAL')
        self.assertEqual(fixture('2155505')['observation']['details']['capacity_gb'],1000)
        ram=fixture()['observation']['details']
        self.assertEqual(ram['total_capacity_gb'],ram['module_count']*ram['capacity_per_module_gb'])

    def test_original_time_and_seller_preserved(self):
        item=fixture('160229354')
        original=json.loads(Path(item['path']).read_text())
        self.assertEqual(item['observation']['observed'],timestamp(original['metadata']['collected_at']))
        self.assertEqual(item['observation']['seller_name'],'Buchmann')
        self.assertIsNone(fixture()['observation']['seller_name'])

    def test_invalid_price_gtin_timestamp(self):
        for value in (0,-1,True,'NaN','Infinity','1.001',None):
            with self.assertRaises(InvalidRecord):money(value)
        for value in ('4711387837833','0000000000000',123):
            with self.assertRaises(InvalidRecord):gtin(value)
        self.assertEqual(gtin('0619659198053'),'00619659198053')
        with self.assertRaises(InvalidRecord):timestamp('2026-10-15T08:00:00')

    def test_malformed_json_and_test_marker_rejected(self):
        with tempfile.TemporaryDirectory() as d:
            p=Path(d)/'bad.json';p.write_text('{bad')
            self.assertIn('rejection',transform_file(p))
            p.write_text(json.dumps({'metadata':{'is_test':True}}))
            self.assertIn('test data',transform_file(p)['rejection'])

    def test_source_price_must_agree(self):
        from backend.transform import restore_legacy
        p=next(RAW.glob('2230728_*.json'))
        record,_=restore_legacy(json.loads(p.read_text()))
        record['price_history']['price_chf']=1
        with self.assertRaisesRegex(InvalidRecord,'differs'):validate(record)


class DatabaseTests(unittest.TestCase):
    def setUp(self):
        self.conn=connect()
        self.schema='midterm_test_'+uuid.uuid4().hex
        self.conn.execute(sql.SQL('CREATE SCHEMA {}').format(sql.Identifier(self.schema)))
        self.conn.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(self.schema)))
        migrate(self.conn)

    def tearDown(self):
        # Only the schema generated by this test is removed. Never public/user data.
        self.conn.execute('SET search_path TO public')
        self.conn.execute(sql.SQL('DROP SCHEMA {} CASCADE').format(sql.Identifier(self.schema)))
        self.conn.close()

    def count(self,table):
        return self.conn.execute(sql.SQL('SELECT count(*) AS n FROM {}').format(sql.Identifier(table))).fetchone()['n']

    def put(self,item):
        return ingest_file(self.conn,Path(item['path']),transformed=item)

    def modified(self,item):
        item=copy.deepcopy(item)
        item['sha256']=hashlib.sha256(uuid.uuid4().bytes).hexdigest()
        return item

    def test_schema_repeat_and_empty_verification(self):
        migrate(self.conn)
        self.assertEqual(self.count('schema_migration'),3)
        result=verification(self.conn)
        self.assertTrue(result['technically_valid'])
        self.assertFalse(result['data_loaded'])
        self.assertFalse(result['ok'])

    def test_real_ingestion_sql_and_repeat(self):
        originals=[fixture(s) for s in ('133486101','160229354','2155505','2199070','2230728','2276243','2277751')]
        first=ingest_directory(self.conn,RAW,transformed=originals)
        self.assertEqual((first['loaded'],first['rejected'],first['error']),(6,1,0))
        self.assertTrue(verification(self.conn)['ok'])
        self.assertEqual((self.count('product'),self.count('retailer_product'),self.count('price_history')),(6,6,6))
        second=ingest_directory(self.conn,RAW,transformed=originals)
        self.assertEqual((second['loaded'],second['duplicate'],second['rejected']),(0,6,1))
        self.assertEqual(self.count('price_history'),6)
        row=self.conn.execute("SELECT * FROM hardware_prices WHERE retailer_sku='160229354'").fetchone()
        self.assertEqual(row['seller_name'],'Buchmann')
        self.assertEqual(row['platform'],'MediaMarkt')

    def test_same_observation_different_file_no_duplicate(self):
        item=fixture();self.put(item)
        self.assertEqual(self.put(self.modified(item))['status'],'duplicate')
        self.assertEqual(self.count('price_history'),1)

    def test_same_price_next_day_is_new_observation(self):
        item=fixture();self.put(item)
        later=self.modified(item);later['observation']['observed']+=timedelta(days=1)
        self.assertEqual(self.put(later)['status'],'loaded')
        self.assertEqual(self.count('price_history'),2)

    def test_backfill_preserves_original_time(self):
        # Two real captured RAM observations, never invented dates/prices.
        items=[transform_file(p) for p in RAW.rglob('2230728_*.json')]
        items=sorted((i for i in items if 'observation' in i),key=lambda i:i['observation']['observed'])
        self.assertGreaterEqual(len({i['observation']['observed'] for i in items}),2)
        old,later=items[0],items[-1]
        self.put(later);self.put(old)
        row=self.conn.execute('SELECT min(collected_at) AS first,min(ingested_at) AS imported FROM price_history').fetchone()
        self.assertEqual(row['first'],old['observation']['observed'])
        self.assertGreater(row['imported'],row['first'])
        self.assertEqual(self.count('price_history'),2)

    def test_conflicting_observation_not_overwritten(self):
        item=fixture();self.put(item)
        conflict=self.modified(item);conflict['observation']['price']+=1
        self.assertEqual(self.put(conflict)['status'],'rejected')
        self.assertEqual(self.count('price_history'),1)

    def test_identifier_disagreement_rejected(self):
        first=fixture('2276243');second=fixture('2277751');self.put(first);self.put(second)
        conflict=self.modified(first)
        conflict['observation']['sku']='ISOLATED-TEST'
        conflict['observation']['mpn']=second['observation']['mpn']
        self.assertEqual(self.put(conflict)['status'],'rejected')
        self.assertEqual(self.count('product'),2)

    def test_technical_conflict_rolls_back(self):
        first=fixture();self.put(first)
        conflict=self.modified(first);conflict['observation']['observed']+=timedelta(days=1)
        conflict['observation']['details']['total_capacity_gb']=32
        self.assertEqual(self.put(conflict)['status'],'rejected')
        self.assertEqual(self.count('price_history'),1)

    def test_missing_identifiers_do_not_merge_names(self):
        first=fixture();first['observation'].update(ean=None,mpn=None)
        second=self.modified(first);second['observation']['sku']='OTHER-ISOLATED-SKU'
        self.put(first);self.put(second)
        self.assertEqual(self.count('product'),2)
        self.assertEqual(self.put(self.modified(first))['status'],'duplicate')

    def test_rejected_file_does_not_stop_valid_file(self):
        bad={'path':'isolated-invalid.json','sha256':'a'*64,'rejection':'Invalid JSON'}
        result=ingest_directory(self.conn,RAW,transformed=[bad,fixture()])
        self.assertEqual((result['rejected'],result['loaded']),(1,1))

    def test_concurrent_rerun(self):
        from concurrent.futures import ThreadPoolExecutor
        item=fixture()
        def worker(_):
            with connect() as conn:
                conn.execute(sql.SQL('SET search_path TO {}').format(sql.Identifier(self.schema)))
                return ingest_file(conn,Path(item['path']),transformed=item)['status']
        with ThreadPoolExecutor(max_workers=2) as pool:
            self.assertEqual(sorted(pool.map(worker,range(2))),['duplicate','loaded'])
        self.assertEqual(self.count('price_history'),1)


if __name__=='__main__':unittest.main()
